import type {
  SupabaseClient,
} from "@supabase/supabase-js";


export type ClaimedAttendanceEmail = {
  id: string;
  student_id: string;
  session_id: string | null;
  notification_type: string;
  recipient: string;
  subject: string;
  message: string;
  attempts: number;
};


type ResendResponse = {
  id?: string;
  message?: string;
  name?: string;
  statusCode?: number;
};


export type AttendanceEmailDeliveryResult = {
  outboxId: string;

  status:
    | "Sent"
    | "Failed";

  providerMessageId?: string;

  retryable?: boolean;

  error?: string;
};


type DeliverAttendanceEmailOptions = {
  admin: SupabaseClient;

  claimed:
    ClaimedAttendanceEmail;

  resendApiKey: string;

  emailFrom: string;
};


